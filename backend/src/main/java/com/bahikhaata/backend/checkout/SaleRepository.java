package com.bahikhaata.backend.checkout;

import java.util.List;
import java.util.Optional;
import java.util.UUID;
import org.springframework.data.domain.Pageable;
import org.springframework.data.jpa.repository.JpaRepository;

public interface SaleRepository extends JpaRepository<Sale, UUID> {

    Optional<Sale> findByBillNo(long billNo);

    /** The highest bill number so far — the next sale takes one more. Empty on the very first sale. */
    Optional<Sale> findTopByOrderByBillNoDesc();

    /** Recent sales, newest first, for the sales screen. */
    List<Sale> findByOrderByCreatedAtDesc(Pageable pageable);
}
